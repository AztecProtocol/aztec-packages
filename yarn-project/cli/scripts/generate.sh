  SEQ_MAX_TX_PER_BLOCK
  SEQ_MAX_TX_PER_CHECKPOINT
  SEQ_BUILD_CHECKPOINT_IF_EMPTY
  SEQ_BLOCK_DURATION_MS
  SEQ_L1_PUBLISHING_TIME_ALLOWANCE_IN_SLOT
  DATA_STORE_MAP_SIZE_KB
