  PUBLIC_OTEL_INCLUDE_METRICS
  PUBLIC_OTEL_OPT_OUT
  PUBLIC_OTEL_EXPORTER_OTLP_METRICS_ENDPOINT
  PUBLIC_OTEL_COLLECT_FROM
  SENTINEL_ENABLED
  L1_CHAIN_ID
  TEST_ACCOUNTS
  SPONSORED_FPC
  TRANSACTIONS_DISABLED
  PROVER_REAL_PROOFS
  PXE_PROVER_ENABLED
  SYNC_SNAPSHOTS_URLS
  SKIP_ARCHIVER_INITIAL_SYNC
  BLOB_ALLOW_EMPTY_SOURCES
  ENABLE_VERSION_CHECK
"

NETWORKS=(devnet testnet mainnet)
ENV_DIR="spartan/environments"

mkdir -p yarn-project/cli/src/config/generated

echo "Generating networks.ts from spartan/environments/*.env..."

{
  cat << 'HEADER'
// Auto-generated from spartan/environments/*.env
// Do not edit manually - run yarn generate to regenerate

HEADER

  for network in "${NETWORKS[@]}"; do
    echo "export const ${network}Config = {"
    extract_keys "$NETWORK_KEYS" "${ENV_DIR}/${network}.env" | format_ts_properties
    echo "} as const;"
    echo ""
  done
} > yarn-project/cli/src/config/generated/networks.ts

echo "Done!"
