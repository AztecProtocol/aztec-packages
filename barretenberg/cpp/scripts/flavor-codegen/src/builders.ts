// Emits `circuit_builders_fwd_generated.hpp`: the forward declaration of each arithmetization's
// trace-block struct, the trace type over it, and the circuit builder over that trace, plus the
// explicit-instantiation lists over the Mega builders.
//
// One flavor owns each arithmetization, so this file is the C++ image of the flavor registry: adding
// an arithmetization adds a builder and updates every instantiation list without a hand edit. The
// subset lists are derived from the same gate kinds the trace headers declare, so "which builders
// have the lookup gate" cannot drift from what the traces actually own.

import * as path from "node:path";

import { writeGenerated } from "./write.js";
import { traceNames, traceShape } from "./trace.js";
import type { Flavor } from "./types.js";

// Gate kinds some Mega arithmetization drops. A kind every arithmetization owns needs no subset list
// -- it would just repeat INSTANTIATE_FOR_EACH_MEGA_BUILDER.
function partitioningGateKinds(megaFlavors: readonly Flavor[]): string[] {
  const kindsOf = (f: Flavor) => new Set(traceShape(f).flatMap((b) => b.kinds));
  const sets = megaFlavors.map(kindsOf);
  const all: string[] = [];
  for (const kinds of sets) {
    for (const kind of kinds) {
      if (!all.includes(kind)) all.push(kind);
    }
  }
  return all.filter((kind) => sets.some((s) => !s.has(kind)));
}

// Snake_case the way the C++ macro names read: "BilinearBatchedEq" -> "BILINEAR_BATCHED_EQ".
function macroSuffix(gateKind: string): string {
  return gateKind.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
}

function emitMacro(name: string, builders: readonly string[]): string[] {
  const lines = [`#define ${name}(MACRO) \\`];
  builders.forEach((b, i) => {
    lines.push(`    MACRO(bb::${b})${i === builders.length - 1 ? "" : " \\"}`);
  });
  return lines;
}

// The common case of a list above: a class template instantiated for each builder, spelled without the
// per-file MACRO it would otherwise need. Templates taking more than the builder (e.g. `bigfield<B, Params>`)
// still need the MACRO form.
function emitClassMacro(name: string, builders: readonly string[]): string[] {
  const lines = [`#define ${name}(Template) \\`];
  builders.forEach((b, i) => {
    lines.push(`    template class Template<bb::${b}>;${i === builders.length - 1 ? "" : " \\"}`);
  });
  return lines;
}

function emitBuildersHeader(traceOwners: readonly Flavor[]): string {
  const lines: string[] = [];
  lines.push("// AUTOGENERATED FILE — do not edit. Regenerate via:");
  lines.push("//   node barretenberg/cpp/scripts/flavor-codegen/dist/main.js");
  lines.push("//");
  lines.push(
    "// Source: barretenberg/cpp/scripts/flavor-codegen/src/builders.ts",
  );
  lines.push("//");
  lines.push(
    "// Included by circuit_builders_fwd.hpp, which declares the class templates named here.",
  );
  lines.push("#pragma once");
  lines.push("");
  lines.push("namespace bb {");
  lines.push("");
  lines.push(
    "// One trace per arithmetization and one builder per trace: the flavor a circuit is built for is",
  );
  lines.push(
    "// part of its type, so a gate the flavor cannot constrain has no block to be appended to.",
  );
  for (const flavor of traceOwners) {
    const { traceTypeName, traceBlockDataName } = traceNames(flavor.family);
    const wrapper =
      flavor.arithmetization === "mega"
        ? "MegaExecutionTraceBlocks_"
        : "UltraExecutionTraceBlocks_";
    lines.push("");
    lines.push(`struct ${traceBlockDataName};`);
    lines.push(`using ${traceTypeName} = ${wrapper}<${traceBlockDataName}>;`);
    const builderArgs =
      flavor.arithmetization === "mega"
        ? `field<Bn254FrParams>, ${traceTypeName}`
        : traceTypeName;
    const builderTemplate =
      flavor.arithmetization === "mega"
        ? "MegaCircuitBuilder_"
        : "UltraCircuitBuilder_";
    lines.push(
      `using ${flavor.builderName} = ${builderTemplate}<${builderArgs}>;`,
    );
  }
  lines.push("");
  lines.push("} // namespace bb");
  lines.push("");

  const megaFlavors = traceOwners.filter((f) => f.arithmetization === "mega");
  const megaBuilders = megaFlavors.map((f) => f.builderName);

  lines.push("/**");
  lines.push(" * @brief Apply MACRO once per Mega arithmetization.");
  lines.push(
    " * @details Drives the explicit-instantiation lists of stdlib primitives and other templates defined",
  );
  lines.push(
    " * in a .cpp: every arithmetization needs its own instantiation, and a new one is picked up here",
  );
  lines.push(" * rather than in ~30 files.");
  lines.push(" */");
  lines.push(...emitMacro("INSTANTIATE_FOR_EACH_MEGA_BUILDER", megaBuilders));
  lines.push("");
  lines.push("/**");
  lines.push(" * @brief Explicitly instantiate a class template for every Mega arithmetization.");
  lines.push(" * @details The common case of the list above, spelled without the per-file macro it would");
  lines.push(" * otherwise need.");
  lines.push(" */");
  lines.push(...emitClassMacro("INSTANTIATE_CLASS_FOR_EACH_MEGA_BUILDER", megaBuilders));
  lines.push("");
  lines.push(
    "// The Mega arithmetizations whose trace owns a given gate kind. A template whose body creates that",
  );
  lines.push(
    "// gate can only be instantiated for these; the others have no block for it.",
  );
  for (const kind of partitioningGateKinds(megaFlavors)) {
    const withKind = megaFlavors
      .filter((f) => traceShape(f).some((b) => b.kinds.includes(kind)))
      .map((f) => f.builderName);
    lines.push("");
    lines.push(
      ...emitMacro(
        `INSTANTIATE_FOR_EACH_MEGA_BUILDER_WITH_${macroSuffix(kind)}`,
        withKind,
      ),
    );
    lines.push("");
    lines.push(
      ...emitClassMacro(
        `INSTANTIATE_CLASS_FOR_EACH_MEGA_BUILDER_WITH_${macroSuffix(kind)}`,
        withKind,
      ),
    );
  }
  lines.push("");

  return lines.join("\n");
}

// Write the builder forward-declaration header to disk; returns its absolute path and whether the
// file changed.
export function generateBuilders(
  traceOwners: readonly Flavor[],
  repoRoot: string,
): { path: string; written: boolean } {
  const header = emitBuildersHeader(traceOwners);
  const outDir = path.join(
    repoRoot,
    "barretenberg",
    "cpp",
    "src",
    "barretenberg",
    "stdlib",
    "primitives",
    "circuit_builders",
    "generated",
  );
  const outFile = path.join(outDir, "circuit_builders_fwd_generated.hpp");
  const written = writeGenerated(outFile, header);
  return { path: outFile, written };
}
