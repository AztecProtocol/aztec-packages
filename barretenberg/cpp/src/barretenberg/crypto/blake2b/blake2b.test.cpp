TEST(crypto_blake2b, test_vectors)
{
    for (const auto& vec : test_vectors) {
        std::vector<uint8_t> input(vec.input.begin(), vec.input.end());
        auto result = crypto::blake2b(input);
        EXPECT_EQ(result, vec.output) << "Failed for input: \"" << vec.input << "\"";
    }
}

TEST(crypto_blake2b, empty_input)
{
    std::vector<uint8_t> input;
    auto result = crypto::blake2b(input);
    EXPECT_EQ(result.size(), 64U);
}

TEST(crypto_blake2b, large_input)
{
    // Test with input larger than one block (128 bytes)
    std::vector<uint8_t> input(256, 0x42);
    auto result = crypto::blake2b(input);
    EXPECT_EQ(result.size(), 64U);
    // Ensure it's not all zeros (basic sanity check)
    bool all_zero = true;
    for (auto byte : result) {
        if (byte != 0) {
            all_zero = false;
            break;
        }
    }
    EXPECT_FALSE(all_zero);
}

TEST(crypto_blake2b, deterministic)
{
    std::vector<uint8_t> input = { 0x01, 0x02, 0x03, 0x04 };
    auto result1 = crypto::blake2b(input);
    auto result2 = crypto::blake2b(input);
    EXPECT_EQ(result1, result2);
}

TEST(crypto_blake2b, different_inputs_different_outputs)
{
    std::vector<uint8_t> input1 = { 0x01 };
    std::vector<uint8_t> input2 = { 0x02 };
    auto result1 = crypto::blake2b(input1);
    auto result2 = crypto::blake2b(input2);
    EXPECT_NE(result1, result2);
}