// Emit fp_dropin_montmul.wgsl: a standalone, bit-exact drop-in montgomery_product_f8
// whose 256x256 multiply runs on the FP32 / FMA path (B=13 TwoProduct schoolbook
// columns), feeding the EXACT same integer Yuval Montgomery reduction the
// reference kernel uses. Conventions identical to ba_stream_walker.S8.pk.wgsl:
// R = 2^260, inputs/outputs 8x u32 little-endian field elements in [0,p).
import fs from 'fs';

const R_INV=[3803,4308,7801,6384,1700,2324,327,444,1220,6327,1154,765,825,4687,1647,6255,240,1621,5669,10];
const P_LIMB=[7495,999,1462,280,5058,1350,455,4653,362,3260,5655,770,7016,2082,1761,5125,305,5015,6419,96];

let s = '';
s += `// AUTO-GENERATED by gen_fp_dropin.mjs — DO NOT EDIT BY HAND.\n`;
s += `// FP B13-TwoProduct multiply + integer Yuval Montgomery reduction.\n`;
s += `// Drop-in for montgomery_product_f8(x,y: array<u32,8>) -> array<u32,8>.\n`;
s += `// Convention: R = 2^260; result = x*y*R^-1 mod p, output in [0,p).\n`;
s += `// Host-validated bit-exact over 100k random pairs (fp_dropin_validate.mjs).\n\n`;

s += `struct BigInt { limbs: array<u32, 20> }\n\n`;

s += `const NUM_WORDS: u32 = 20u;\nconst WORD_SIZE: u32 = 13u;\nconst MASK: u32 = 8191u;\n`;
s += `const TWO_POW_WORD_SIZE: u32 = 8192u;\nconst N0: u32 = 905u;\n\n`;
for (let i=0;i<20;i++) s += `const R_INV_${i}: u32 = ${R_INV[i]}u;\n`;
s += `\n`;
for (let i=0;i<20;i++) s += `const P_LIMB_${i}: u32 = ${P_LIMB[i]}u;\n`;
s += `\n`;

// FP constants for the B13 split (CHI13 = 2^36 forces rounding at weight 2^13).
s += `const CHI13: f32 = ${(2**(23+13))}.0;     // 2^36\n`;
s += `const RINV13: f32 = ${1/2**13};            // 2^-13\n\n`;

// ---- BigInt helpers needed by conditional_reduce ----
s += `fn bigint_sub(a: ptr<function, BigInt>, b: ptr<function, BigInt>, res: ptr<function, BigInt>) -> u32 {\n`;
s += `    var borrow: u32 = 0u;\n`;
s += `    for (var i: u32 = 0u; i < NUM_WORDS; i = i + 1u) {\n`;
s += `        (*res).limbs[i] = (*a).limbs[i] - (*b).limbs[i] - borrow;\n`;
s += `        if ((*a).limbs[i] < ((*b).limbs[i] + borrow)) {\n`;
s += `            (*res).limbs[i] += TWO_POW_WORD_SIZE;\n`;
s += `            borrow = 1u;\n`;
s += `        } else { borrow = 0u; }\n`;
s += `    }\n    return borrow;\n}\n\n`;

s += `fn bigint_gt(x: ptr<function, BigInt>, y: ptr<function, BigInt>) -> u32 {\n`;
s += `    for (var idx = 0u; idx < NUM_WORDS; idx ++) {\n`;
s += `        var i = NUM_WORDS - 1u - idx;\n`;
s += `        if ((*x).limbs[i] < (*y).limbs[i]) { return 0u; }\n`;
s += `        else if ((*x).limbs[i] > (*y).limbs[i]) { return 1u; }\n`;
s += `    }\n    return 0u;\n}\n\n`;

s += `fn bigint_eq(x: ptr<function, BigInt>, y: ptr<function, BigInt>) -> bool {\n`;
s += `    for (var i = 0u; i < NUM_WORDS; i ++) {\n`;
s += `        if ((*x).limbs[i] != (*y).limbs[i]) { return false; }\n`;
s += `    }\n    return true;\n}\n\n`;

s += `fn get_p() -> BigInt {\n    var p: BigInt;\n`;
for (let i=0;i<20;i++) s += `    p.limbs[${i}] = P_LIMB_${i};\n`;
s += `    return p;\n}\n\n`;

s += `fn conditional_reduce(x: ptr<function, BigInt>) -> BigInt {\n`;
s += `    var p = get_p();\n`;
s += `    var x_gt_y = bigint_gt(x, &p);\n`;
s += `    var x_eq_y = bigint_eq(x, &p);\n`;
s += `    if (x_gt_y == 1u || x_eq_y) {\n`;
s += `        var res: BigInt;\n        bigint_sub(x, &p, &res);\n        return res;\n    }\n`;
s += `    return *x;\n}\n\n`;

// ---- unpack256_to_limbs / pack_limbs_to_256 (verbatim from reference) ----
s += `fn unpack256_to_limbs(w: array<u32, 8>) -> BigInt {\n`;
s += `    var b: BigInt;\n`;
s += `    b.limbs[0u] = (w[0u] >> 0u) & 8191u;\n`;
s += `    b.limbs[1u] = (w[0u] >> 13u) & 8191u;\n`;
s += `    b.limbs[2u] = ((w[0u] >> 26u) | (w[1u] << 6u)) & 8191u;\n`;
s += `    b.limbs[3u] = (w[1u] >> 7u) & 8191u;\n`;
s += `    b.limbs[4u] = ((w[1u] >> 20u) | (w[2u] << 12u)) & 8191u;\n`;
s += `    b.limbs[5u] = (w[2u] >> 1u) & 8191u;\n`;
s += `    b.limbs[6u] = (w[2u] >> 14u) & 8191u;\n`;
s += `    b.limbs[7u] = ((w[2u] >> 27u) | (w[3u] << 5u)) & 8191u;\n`;
s += `    b.limbs[8u] = (w[3u] >> 8u) & 8191u;\n`;
s += `    b.limbs[9u] = ((w[3u] >> 21u) | (w[4u] << 11u)) & 8191u;\n`;
s += `    b.limbs[10u] = (w[4u] >> 2u) & 8191u;\n`;
s += `    b.limbs[11u] = (w[4u] >> 15u) & 8191u;\n`;
s += `    b.limbs[12u] = ((w[4u] >> 28u) | (w[5u] << 4u)) & 8191u;\n`;
s += `    b.limbs[13u] = (w[5u] >> 9u) & 8191u;\n`;
s += `    b.limbs[14u] = ((w[5u] >> 22u) | (w[6u] << 10u)) & 8191u;\n`;
s += `    b.limbs[15u] = (w[6u] >> 3u) & 8191u;\n`;
s += `    b.limbs[16u] = (w[6u] >> 16u) & 8191u;\n`;
s += `    b.limbs[17u] = ((w[6u] >> 29u) | (w[7u] << 3u)) & 8191u;\n`;
s += `    b.limbs[18u] = (w[7u] >> 10u) & 8191u;\n`;
s += `    b.limbs[19u] = (w[7u] >> 23u) & 8191u;\n`;
s += `    return b;\n}\n\n`;

s += `fn pack_limbs_to_256(bp: ptr<function, BigInt>) -> array<u32, 8> {\n`;
s += `    let b = *bp;\n    var w: array<u32, 8>;\n`;
s += `    w[0u] = (b.limbs[0u] & 8191u) | ((b.limbs[1u] & 8191u) << 13u) | ((b.limbs[2u] & 8191u) << 26u);\n`;
s += `    w[1u] = ((b.limbs[2u] & 8191u) >> 6u) | ((b.limbs[3u] & 8191u) << 7u) | ((b.limbs[4u] & 8191u) << 20u);\n`;
s += `    w[2u] = ((b.limbs[4u] & 8191u) >> 12u) | ((b.limbs[5u] & 8191u) << 1u) | ((b.limbs[6u] & 8191u) << 14u) | ((b.limbs[7u] & 8191u) << 27u);\n`;
s += `    w[3u] = ((b.limbs[7u] & 8191u) >> 5u) | ((b.limbs[8u] & 8191u) << 8u) | ((b.limbs[9u] & 8191u) << 21u);\n`;
s += `    w[4u] = ((b.limbs[9u] & 8191u) >> 11u) | ((b.limbs[10u] & 8191u) << 2u) | ((b.limbs[11u] & 8191u) << 15u) | ((b.limbs[12u] & 8191u) << 28u);\n`;
s += `    w[5u] = ((b.limbs[12u] & 8191u) >> 4u) | ((b.limbs[13u] & 8191u) << 9u) | ((b.limbs[14u] & 8191u) << 22u);\n`;
s += `    w[6u] = ((b.limbs[14u] & 8191u) >> 10u) | ((b.limbs[15u] & 8191u) << 3u) | ((b.limbs[16u] & 8191u) << 16u) | ((b.limbs[17u] & 8191u) << 29u);\n`;
s += `    w[7u] = ((b.limbs[17u] & 8191u) >> 3u) | ((b.limbs[18u] & 8191u) << 10u) | ((b.limbs[19u] & 8191u) << 23u);\n`;
s += `    return w;\n}\n\n`;

// ---- The FP multiply + integer reduce, all inline in montgomery_product ----
s += `// montgomery_product on 20x13-bit BigInt operands. The 256x256 product is\n`;
s += `// formed on the FP32 FMA pipe: each 13-bit limb product x_i*y_j is split by a\n`;
s += `// TwoProduct (CHI13 = 2^36 rounds at weight 2^13) into a non-negative hi digit\n`;
s += `// (hi/2^13 in [0,2^13)) and a SIGNED lo residual, with hi + lo == x_i*y_j\n`;
s += `// exactly. Two f32 accumulators per column (hAcc=sum hi/2^13, lAcc=sum lo) stay\n`;
s += `// < 2^18 (<= 20 terms), so every FP add is exact. The raw schoolbook column\n`;
s += `// t_k = sum_{i+j=k} x_i*y_j is then recombined in wrapping u32 as\n`;
s += `// t_k = u32(hAcc)*8192 + bitcast<u32>(i32(lAcc)); the true value is non-negative\n`;
s += `// < 2^31 so the two's-complement wrap is exact. These raw columns are exactly\n`;
s += `// what the integer Karatsuba produced, so the unchanged Yuval reduce below is\n`;
s += `// bit-identical to the reference montgomery_product.\n`;
s += `fn montgomery_product(x_ptr: ptr<function, BigInt>, y_ptr: ptr<function, BigInt>) -> BigInt {\n`;
// declare x/y limbs as f32
for (let i=0;i<20;i++) s += `    let xf${i}: f32 = f32((*x_ptr).limbs[${i}u]);\n`;
for (let i=0;i<20;i++) s += `    let yf${i}: f32 = f32((*y_ptr).limbs[${i}u]);\n`;
// column accumulators
for (let k=0;k<39;k++) s += `    var hAcc${k}: f32 = 0.0;\n`;
for (let k=0;k<39;k++) s += `    var lAcc${k}: f32 = 0.0;\n`;
// products
for (let i=0;i<20;i++) for (let j=0;j<20;j++){
  const k=i+j;
  s += `    { let pr = fma(xf${i}, yf${j}, CHI13); let hi = pr - CHI13; let lo = fma(xf${i}, yf${j}, -hi);`;
  s += ` hAcc${k} = hAcc${k} + hi * RINV13; lAcc${k} = lAcc${k} + lo; }\n`;
}
// recombine each column to a u32 raw schoolbook column t{k}
for (let k=0;k<39;k++)
  s += `    let t${k}_raw: u32 = (u32(hAcc${k}) * 8192u) + bitcast<u32>(i32(lAcc${k}));\n`;
// move into mutable t vars t0..t39 (t39 starts 0)
for (let k=0;k<39;k++) s += `    var t${k}: u32 = t${k}_raw;\n`;
s += `    var t39: u32 = 0u;\n`;

// ---- Yuval reduce: 19 Yuval calls + 1 standard (mirror of reference) ----
for (let i=0;i<19;i++){
  s += `    {\n`;
  s += `        let t_mask: u32 = t${i} & MASK;\n`;
  s += `        let carry: u32 = t${i} >> WORD_SIZE;\n`;
  s += `        t${i+1} = t${i+1} + t_mask * R_INV_0 + carry;\n`;
  for (let j=1;j<20;j++) s += `        t${i+1+j} = t${i+1+j} + t_mask * R_INV_${j};\n`;
  s += `    }\n`;
}
// standard reduce i=19
s += `    {\n`;
s += `        let t_mask: u32 = t19 & MASK;\n`;
s += `        let k_std: u32 = (t_mask * N0) & MASK;\n`;
s += `        t19 = t19 + k_std * P_LIMB_0;\n`;
s += `        t20 = t20 + k_std * P_LIMB_1 + (t19 >> WORD_SIZE);\n`;
for (let j=2;j<20;j++) s += `        t${19+j} = t${19+j} + k_std * P_LIMB_${j};\n`;
s += `    }\n`;

// final canonicalization carry pass t20..t39
s += `    var c: u32 = 0u;\n`;
for (let k=20;k<40;k++){
  s += `    { let v: u32 = t${k} + c; c = v >> WORD_SIZE; t${k} = v & MASK; }\n`;
}
// repack
s += `    var sres: BigInt;\n`;
for (let k=0;k<20;k++) s += `    sres.limbs[${k}u] = t${20+k};\n`;
s += `    return conditional_reduce(&sres);\n`;
s += `}\n\n`;

// ---- montgomery_product_f8 wrapper (same signature as the walker calls) ----
s += `fn montgomery_product_f8(x: array<u32, 8>, y: array<u32, 8>) -> array<u32, 8> {\n`;
s += `    var x20: BigInt = unpack256_to_limbs(x);\n`;
s += `    var y20: BigInt = unpack256_to_limbs(y);\n`;
s += `    var r: BigInt = montgomery_product(&x20, &y20);\n`;
s += `    return pack_limbs_to_256(&r);\n`;
s += `}\n`;

