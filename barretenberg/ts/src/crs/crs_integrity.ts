function arraysEqual(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return false;
  }
  return true;
}

/**
 * Spot-check compressed G1 CRS data by verifying the first two elements match known values.
 * This is NOT a full integrity check of the entire file.
 * Throws on mismatch.
 */
export function spotCheckG1Data(data: Uint8Array): void {
  if (data.length < 32) {
    throw new Error(`CRS G1 data too short: expected at least 32 bytes, got ${data.length}`);
  }
  const first = data.slice(0, 32);
  if (!arraysEqual(first, BN254_G1_FIRST_ELEMENT_COMPRESSED)) {
    throw new Error('CRS integrity check failed: first G1 element does not match expected generator point');
  }
  if (data.length >= 64) {
    const second = data.slice(32, 64);
    if (!arraysEqual(second, BN254_G1_SECOND_ELEMENT_COMPRESSED)) {
      throw new Error('CRS integrity check failed: second G1 element does not match expected value');
    }
  }
}

