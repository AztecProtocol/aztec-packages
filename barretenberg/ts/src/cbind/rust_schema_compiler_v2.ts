/**
 * Rust schema compiler v2 - rebuilt from first principles
 *
 * Design philosophy:
 * 1. Two-pass approach: discover all types first, then generate
 * 2. All byte arrays become Vec<u8> (avoid serde limitations)
 * 3. Preserve type name casing (e.g., ClientIVCProof)
 * 4. Generate constructors only for command types
 */

interface RustType {
  rustType: string;
  needsSerdeBytes: boolean;
}

interface TypeDef {
  name: string;
  fields: Array<{
    name: string;
    originalName: string;
    rustType: string;
    needsSerdeBytes: boolean
  }>;
  isCommand: boolean;
}

export class RustSchemaCompilerV2 {
  private types = new Map<string, TypeDef>();
  private commands: Array<{ name: string; typeName: string }> = [];
  private responses: Array<{ name: string; typeName: string }> = [];
  private schema: any = null;

  processApiSchema(commandsSchema: any, responsesSchema: any): void {
    // Store the full schema
    this.schema = {
      __typename: 'Api',
      commands: commandsSchema,
      responses: responsesSchema,
    };
  }

  compile(): string {
    if (!this.schema) {
      throw new Error('Must call processApiSchema before compile');
    }

    // Pass 1: Discover all types
    this.discoverTypes(this.schema);

    // Pass 2: Generate code
    const parts: string[] = [
      '//! AUTOGENERATED FILE - DO NOT EDIT',
      '//! Generated from msgpack schema',
      '',
      'use serde::{Deserialize, Serialize};',
      '',
      '// Helper module for efficient binary serialization',
      'mod serde_bytes {',
      '    use serde::{Deserialize, Deserializer, Serializer};',
      '',
      '    pub fn serialize<S>(bytes: &Vec<u8>, serializer: S) -> Result<S::Ok, S::Error>',
      '    where',
      '        S: Serializer,',
      '    {',
      '        serializer.serialize_bytes(bytes)',
      '    }',
      '',
      '    pub fn deserialize<\'de, D>(deserializer: D) -> Result<Vec<u8>, D::Error>',
      '    where',
      '        D: Deserializer<\'de>,',
      '    {',
      '        <Vec<u8>>::deserialize(deserializer)',
      '    }',
      '}',
      '',
    ];

    // Generate type definitions (sorted for consistency)
    const sortedTypes = Array.from(this.types.values()).sort((a, b) => a.name.localeCompare(b.name));
    for (const typeDef of sortedTypes) {
      parts.push(this.generateTypeDef(typeDef));
      parts.push('');
    }

    // Generate Command enum
    parts.push(this.generateCommandEnum());
    parts.push('');

    // Generate Response enum
    parts.push(this.generateResponseEnum());
    parts.push('');

    return parts.join('\n');
  }

  private discoverTypes(schema: any): void {
    const commands = schema.commands[1] as Array<[string, any]>;
    const responses = schema.responses[1] as Array<[string, any]>;

    // Process commands
    for (const [name, commandSchema] of commands) {
      this.commands.push({ name, typeName: name });
      this.discoverType(name, commandSchema, true);
    }

    // Process responses
    for (const [name, responseSchema] of responses) {
      this.responses.push({ name, typeName: name });

      // Handle reference-only responses (e.g., "CircuitComputeVkResponse")
      if (typeof responseSchema === 'string') {
        // This is a reference to an already-defined type, skip
        continue;
      }

      this.discoverType(name, responseSchema, false);
    }
  }

  private discoverType(name: string, schema: any, isCommand: boolean): void {
    // Convert type name to PascalCase (e.g., affine_element -> AffineElement)
    const typeName = this.toPascalCase(name);

    if (this.types.has(typeName)) {
      return; // Already processed
    }

    if (typeof schema === 'string') {
      // This is a reference to another type, not a definition
      return;
    }

    if (typeof schema === 'object' && schema.__typename) {
      // This is an object schema with fields
      const fields: TypeDef['fields'] = [];

      for (const [key, value] of Object.entries(schema)) {
        if (key === '__typename') continue;

        const rustType = this.resolveType(value);
        fields.push({
          name: this.toSnakeCase(key),
          originalName: key,
          rustType: rustType.rustType,
          needsSerdeBytes: rustType.needsSerdeBytes,
        });
      }

      this.types.set(typeName, { name: typeName, fields, isCommand });
    }
  }

  private resolveType(schema: any): RustType {
    // Handle string references
    if (typeof schema === 'string') {
      // Map known primitive types
      switch (schema) {
        case 'bool':
          return { rustType: 'bool', needsSerdeBytes: false };
        case 'string':
          return { rustType: 'String', needsSerdeBytes: false };
        case 'unsigned int':
        case 'int':
          return { rustType: 'u32', needsSerdeBytes: false };
        case 'unsigned long':
          return { rustType: 'u64', needsSerdeBytes: false };
        case 'unsigned short':
          return { rustType: 'u16', needsSerdeBytes: false };
        case 'unsigned char':
          return { rustType: 'u8', needsSerdeBytes: false };
        case 'double':
          return { rustType: 'f64', needsSerdeBytes: false };
        default:
          // Custom type reference - convert to PascalCase
          return { rustType: this.toPascalCase(schema), needsSerdeBytes: false };
      }
    }

    // Handle arrays
    if (Array.isArray(schema)) {
      const [type, ...args] = schema;

      switch (type) {
        case 'vector':
          const [elemType] = args[0] as [any];
          if (elemType === 'unsigned char') {
            return { rustType: 'Vec<u8>', needsSerdeBytes: true };
          }
          const elemRust = this.resolveType(elemType);
          return { rustType: `Vec<${elemRust.rustType}>`, needsSerdeBytes: false };

        case 'array':
          const [arrayElemType, size] = args[0] as [any, number];
          // ALWAYS use Vec<u8> for byte arrays to avoid serde limitations
          if (arrayElemType === 'unsigned char') {
            return { rustType: 'Vec<u8>', needsSerdeBytes: true };
          }
          // For other arrays, use Vec if size > 32 (serde limitation)
          const arrayElemRust = this.resolveType(arrayElemType);
          if (size > 32) {
            return { rustType: `Vec<${arrayElemRust.rustType}>`, needsSerdeBytes: false };
          }
          return { rustType: `[${arrayElemRust.rustType}; ${size}]`, needsSerdeBytes: false };

        case 'alias':
          // Aliases like ["fr", "bin32"] are just Vec<u8>
          return { rustType: 'Vec<u8>', needsSerdeBytes: true };

        case 'optional':
          const [optType] = args[0] as [any];
          const optRust = this.resolveType(optType);
          return { rustType: `Option<${optRust.rustType}>`, needsSerdeBytes: false };

        case 'shared_ptr':
          // Shared pointers are just the underlying type in Rust
          const [ptrType] = args[0] as [any];
          return this.resolveType(ptrType);

        default:
          throw new Error(`Unknown array type: ${type}`);
      }
    }

    // Handle inline object schemas
    if (typeof schema === 'object' && schema.__typename) {
      const typeName = schema.__typename as string;

      // Recursively discover this type
      this.discoverType(typeName, schema, false);

      return { rustType: this.toPascalCase(typeName), needsSerdeBytes: false };
    }

    throw new Error(`Cannot resolve type: ${JSON.stringify(schema)}`);
  }

  private generateTypeDef(typeDef: TypeDef): string {
    const fields = typeDef.fields.map(field => {
      let attrs = '';

      // Add rename attribute if needed
      if (field.originalName !== field.name) {
        attrs += `    #[serde(rename = "${field.originalName}")]\n`;
      }

      // Add serde_bytes for Vec<u8>
      if (field.needsSerdeBytes) {
        attrs += `    #[serde(with = "serde_bytes")]\n`;
      }

      return `${attrs}    pub ${field.name}: ${field.rustType},`;
    });

    // Add __typename field for all types
    const typenameField = `    #[serde(rename = "__typename")]\n    pub type_name: String,`;
    const allFields = [typenameField, ...fields];

    // Generate constructor for command types
    const constructor = typeDef.isCommand ? this.generateConstructor(typeDef) : '';

    return `/// ${typeDef.name} type from msgpack schema
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ${typeDef.name} {
${allFields.join('\n')}
}
${constructor}`;
  }

  private generateConstructor(typeDef: TypeDef): string {
    const params = typeDef.fields.map(f => `${f.name}: ${f.rustType}`).join(', ');
    const fieldInits = [
      `            type_name: "${typeDef.name}".to_string(),`,
      ...typeDef.fields.map(f => `            ${f.name},`),
    ];

    return `
impl ${typeDef.name} {
    pub fn new(${params}) -> Self {
        Self {
${fieldInits.join('\n')}
        }
    }
}`;
  }

  private generateCommandEnum(): string {
    const variants = this.commands.map(c => `    ${c.typeName}(${c.typeName}),`);

    const serializeCases = this.commands.map(c =>
      `            Command::${c.typeName}(data) => {
                tuple.serialize_element("${c.typeName}")?;
                tuple.serialize_element(data)?;
            }`
    );

    const deserializeCases = this.commands.map(c =>
      `                    "${c.typeName}" => {
                        let data = seq.next_element()?
                            .ok_or_else(|| serde::de::Error::invalid_length(1, &self))?;
                        Ok(Command::${c.typeName}(data))
                    }`
    );

    const variantNames = this.commands.map(c => `"${c.typeName}"`).join(', ');

    return `/// Command enum wrapping all possible commands
#[derive(Debug, Clone)]
pub enum Command {
${variants.join('\n')}
}

impl Serialize for Command {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        use serde::ser::SerializeTuple;
        let mut tuple = serializer.serialize_tuple(2)?;

        match self {
${serializeCases.join('\n')}
        }

        tuple.end()
    }
}

impl<'de> Deserialize<'de> for Command {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        use serde::de::{SeqAccess, Visitor};

        struct CommandVisitor;

        impl<'de> Visitor<'de> for CommandVisitor {
            type Value = Command;

            fn expecting(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {
                formatter.write_str("a 2-element array [command_name, payload]")
            }

            fn visit_seq<A>(self, mut seq: A) -> Result<Self::Value, A::Error>
            where
                A: SeqAccess<'de>,
            {
                let name: String = seq.next_element()?
                    .ok_or_else(|| serde::de::Error::invalid_length(0, &self))?;

                match name.as_str() {
${deserializeCases.join('\n')}
                    _ => Err(serde::de::Error::unknown_variant(&name, &[
                        ${variantNames}
                    ])),
                }
            }
        }

        deserializer.deserialize_tuple(2, CommandVisitor)
    }
}`;
  }

  private generateResponseEnum(): string {
    const variants = this.responses.map(r => `    ${r.typeName}(${r.typeName}),`);

    const serializeCases = this.responses.map(r =>
      `            Response::${r.typeName}(data) => {
                tuple.serialize_element("${r.typeName}")?;
                tuple.serialize_element(data)?;
            }`
    );

    const deserializeCases = this.responses.map(r =>
      `                    "${r.typeName}" => {
                        let data = seq.next_element()?
                            .ok_or_else(|| serde::de::Error::invalid_length(1, &self))?;
                        Ok(Response::${r.typeName}(data))
                    }`
    );

    const variantNames = this.responses.map(r => `"${r.typeName}"`).join(', ');

    return `/// Response enum wrapping all possible responses
#[derive(Debug, Clone)]
pub enum Response {
${variants.join('\n')}
}

impl Serialize for Response {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        use serde::ser::SerializeTuple;
        let mut tuple = serializer.serialize_tuple(2)?;

        match self {
${serializeCases.join('\n')}
        }

        tuple.end()
    }
}

impl<'de> Deserialize<'de> for Response {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        use serde::de::{SeqAccess, Visitor};

        struct ResponseVisitor;

        impl<'de> Visitor<'de> for ResponseVisitor {
            type Value = Response;

            fn expecting(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {
                formatter.write_str("a 2-element array [response_name, payload]")
            }

            fn visit_seq<A>(self, mut seq: A) -> Result<Self::Value, A::Error>
            where
                A: SeqAccess<'de>,
            {
                let name: String = seq.next_element()?
                    .ok_or_else(|| serde::de::Error::invalid_length(0, &self))?;

                match name.as_str() {
${deserializeCases.join('\n')}
                    _ => Err(serde::de::Error::unknown_variant(&name, &[
                        ${variantNames}
                    ])),
                }
            }
        }

        deserializer.deserialize_tuple(2, ResponseVisitor)
    }
}`;
  }

  private toSnakeCase(s: string): string {
    return s.replace(/([A-Z])/g, '_$1').toLowerCase().replace(/^_/, '');
  }

  private toPascalCase(s: string): string {
    // If already in PascalCase (e.g., "ClientIVCProof"), preserve it
    if (!s.includes('_') && s.charAt(0) === s.charAt(0).toUpperCase()) {
      return s;
    }

    // Convert snake_case to PascalCase (e.g., "affine_element" -> "AffineElement")
    return s.split('_').map(part =>
      part.charAt(0).toUpperCase() + part.slice(1).toLowerCase()
    ).join('');
  }
}

export function createRustCompilerV2(): RustSchemaCompilerV2 {
  return new RustSchemaCompilerV2();
}
