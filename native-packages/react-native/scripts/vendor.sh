#!/usr/bin/env bash
# Fills third_party/ with the sources the package's native module compiles in the app:
#   - kv-sqlite's service (native-packages/kv-sqlite), the PXE's store: its sources, its FFI and dispatch
#     generated from its schema, and msgpack-c's headers at the commit kv-sqlite builds with;
#   - SQLite3 Multiple Ciphers' amalgamation (the release kv-sqlite builds, so a store has one format in a
#     browser, in node and on a phone), with aztec_sqlite_prefix.h, which renames every symbol it exports to
#     aztec_<name>: an app may link another SQLite or libsodium, whose symbols would clash;
#   - ipc-runtime's JSI binding (ipc-runtime/cpp/jsi).
set -euo pipefail

cd "$(dirname "$0")/.."
root=$(git rev-parse --show-toplevel)

# As native-packages/kv-sqlite/cpp/CMakeLists.txt fetches them.
mc_version=2.6.1
sqlite_version=3.54.0
mc_sha256=3f25af603566a23c821d8e581778b5ece2a541d2435776de57b8d845c176815a
msgpack_commit=8c602e8579c7e7d65d6f9c6703c9699db3fb0488

out=third_party/sqlite3mc
if [ ! -f "$out/aztec_sqlite_prefix.h" ]; then
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  curl -sSfL -o "$tmp/mc.zip" \
    "https://github.com/utelle/SQLite3MultipleCiphers/releases/download/v$mc_version/sqlite3mc-$mc_version-sqlite-$sqlite_version-amalgamation.zip"
  echo "$mc_sha256  $tmp/mc.zip" | sha256sum -c --quiet
  mkdir -p "$tmp/src"
  python3 -m zipfile -e "$tmp/mc.zip" "$tmp/src"
  rm -rf "$out"
  mkdir -p "$out"
  cp "$tmp/src/sqlite3mc_amalgamation.c" "$tmp/src/sqlite3mc_amalgamation.h" "$out/"

  # Every global the amalgamation defines, on this machine, plus the implementation tables other machines
  # select (the crypto code picks one per CPU).
  ${CC:-cc} -c -O0 -w -DSQLITE_THREADSAFE=1 -DSQLITE_DQS=0 -DSQLITE_OMIT_LOAD_EXTENSION=1 \
    "$out/sqlite3mc_amalgamation.c" -o "$tmp/mc.o"
  {
    nm -g --defined-only "$tmp/mc.o" | awk '{print $3}'
    grep -oE '\bcrypto_[A-Za-z0-9_]+_implementation\b' "$out/sqlite3mc_amalgamation.c"
  } | sort -u >"$tmp/symbols"
  {
    echo "// Generated by scripts/vendor.sh: SQLite3 Multiple Ciphers' exported symbols, renamed."
    echo "#pragma once"
    while read -r symbol; do
      echo "#define $symbol aztec_$symbol"
    done <"$tmp/symbols"
  } >"$out/aztec_sqlite_prefix.h"

  ${CC:-cc} -c -O0 -w -include "$out/aztec_sqlite_prefix.h" -DSQLITE_THREADSAFE=1 -DSQLITE_DQS=0 \
    -DSQLITE_OMIT_LOAD_EXTENSION=1 "$out/sqlite3mc_amalgamation.c" -o "$tmp/prefixed.o"
  if nm -g --defined-only "$tmp/prefixed.o" | awk '{print $3}' | grep -v '^aztec_'; then
    echo "vendor.sh: the symbols above escaped aztec_sqlite_prefix.h" >&2
    exit 1
  fi
fi

if [ ! -f third_party/msgpack-c/include/msgpack.hpp ]; then
  rm -rf third_party/msgpack-c.tmp
  git init -q third_party/msgpack-c.tmp
  git -C third_party/msgpack-c.tmp fetch -q --depth 1 https://github.com/msgpack/msgpack-c.git $msgpack_commit
  git -C third_party/msgpack-c.tmp checkout -q FETCH_HEAD
  rm -rf third_party/msgpack-c
  mkdir -p third_party/msgpack-c
  mv third_party/msgpack-c.tmp/include third_party/msgpack-c/include
  rm -rf third_party/msgpack-c.tmp
fi

kv=$root/native-packages/kv-sqlite
rm -rf third_party/kv-sqlite
mkdir -p third_party/kv-sqlite
cp "$kv"/cpp/src/kv/{store.cpp,store.hpp,kv_service.cpp,files_native.cpp,sha256.hpp} third_party/kv-sqlite/
"$root/ipc-codegen/bin/ipc-codegen.mjs" \
  --schema "$kv/kv_schema.jsonc" --lang cpp --out third_party/kv-sqlite/generated \
  --server --cpp-namespace aztec::kv --cpp-include-dir generated --ffi=kv_sqlite >/dev/null
# The generated code's support headers, where its `#include "ipc_codegen/..."` finds them.
cp -R "$root/ipc-runtime/cpp/ipc_codegen" third_party/kv-sqlite/generated/

mkdir -p third_party/ipc-runtime-jsi
cp "$root/ipc-runtime/cpp/jsi/ipc_runtime_jsi.hpp" "$root/ipc-runtime/cpp/jsi/ipc_runtime_jsi.cpp" third_party/ipc-runtime-jsi/
mkdir -p third_party/ipc-runtime-jsi/ipc_runtime
cp "$root/ipc-runtime/cpp/ipc_runtime/ffi_abi.h" third_party/ipc-runtime-jsi/ipc_runtime/
